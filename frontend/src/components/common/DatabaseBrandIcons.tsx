export function getDatabaseBrandIcon(
  conn?: Partial<Connection> | null,
  dbTypeOverride?: string,
  className = 'w-3.5 h-3.5 shrink-0'
) {
  const dbType = (dbTypeOverride || (conn as any)?.dbType || '').toLowerCase();
  const name = (conn?.name || '').toLowerCase();
  const tags = (conn?.tags || []).join(' ').toLowerCase();
  const port = conn?.port || 0;

  if (dbType === 'clickhouse') {
    return <ClickHouseIcon className={className} />;
  }
  if (dbType === 'postgres' || dbType === 'postgresql') {
    return <PostgresIcon className={className} />;
  }
  if (dbType === 'mysql' || dbType === 'mariadb') {
    return <MySQLIcon className={className} />;
  }
  if (dbType === 'sqlite') {
    return <SQLiteIcon className={className} />;
  }

  // Fallback to name/tags/port inspection if dbType is not explicitly provided
  if (
    port === 9443 ||
    port === 8443 ||
    port === 8123 ||
    port === 9000 ||
    port === 21426 ||
    name.includes('clickhouse') ||
    tags.includes('clickhouse') ||
    name.includes('ndm') ||
    name.includes('fusion') ||
    name.includes('redhat') ||
    name.includes('cloudpond')
  ) {
    return <ClickHouseIcon className={className} />;
  }

  if (
    port === 5432 ||
    port === 6432 ||
    name.includes('postgres') ||
    tags.includes('postgres') ||
    name.includes('pgsql') ||
    name.includes('citus')
  ) {
    return <PostgresIcon className={className} />;
  }

  if (
    port === 3306 ||
    name.includes('mysql') ||
    tags.includes('mysql') ||
    name.includes('mariadb')
  ) {
    return <MySQLIcon className={className} />;
  }

  if (
    name.includes('sqlite') ||
    tags.includes('sqlite') ||
    (conn?.host && (conn.host.endsWith('.db') || conn.host.endsWith('.sqlite')))
  ) {
    return <SQLiteIcon className={className} />;
  }

  return <Database className={`${className} text-purple-400`} />;
}
